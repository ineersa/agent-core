<?php

declare(strict_types=1);

namespace Ineersa\CodingAgent\Build;

/**
 * Canonical application version/build identity for source, PHAR, and fused native.
 *
 * Resolution order:
 *   1. Generated identity file written into staged builds (PHAR / static).
 *   2. HATFIELD_BUILD_VERSION / HATFIELD_BUILD_COMMIT environment overrides.
 *   3. Source-tree development identity (version "dev" + best-effort git SHA).
 */
final class ApplicationBuildIdentity
{
    public const string GENERATED_RELATIVE_PATH = 'src/CodingAgent/Build/build-identity.generated.php';

    public function __construct(
        public readonly string $version,
        public readonly string $commit,
    ) {
    }

    public static function resolve(?string $projectDir = null): self
    {
        $generated = self::loadGenerated($projectDir);
        if (null !== $generated) {
            return $generated;
        }

        $envVersion = self::env('HATFIELD_BUILD_VERSION');
        $envCommit = self::env('HATFIELD_BUILD_COMMIT');
        if (null !== $envVersion || null !== $envCommit) {
            return new self(
                version: $envVersion ?? 'dev',
                commit: self::normalizeCommit($envCommit ?? self::detectGitCommit($projectDir)),
            );
        }

        return new self(
            version: 'dev',
            commit: self::detectGitCommit($projectDir),
        );
    }

    /**
     * Value for Symfony Console Application::setVersion() / --version.
     *
     * Examples:
     *   1.2.3 (commit abcdef1)
     *   dev (commit abcdef1)
     *   dev (commit unknown)
     */
    public function displayVersion(): string
    {
        return \sprintf('%s (commit %s)', $this->version, $this->commit);
    }

    /**
     * PHP source for the generated identity file embedded into packaged artifacts.
     */
    public static function generatePhpSource(string $version, string $commit): string
    {
        $versionExport = var_export($version, true);
        $commitExport = var_export(self::normalizeCommit($commit), true);

        return <<<PHP
<?php

declare(strict_types=1);

// Generated by Hatfield distribution packaging. Do not edit by hand.
return [
    'version' => {$versionExport},
    'commit' => {$commitExport},
];

PHP;
    }

    private static function loadGenerated(?string $projectDir): ?self
    {
        $candidates = [];
        // Prefer the file next to this class (works for source + staged PHAR tree).
        $candidates[] = __DIR__.'/build-identity.generated.php';
        if (null !== $projectDir && '' !== $projectDir) {
            $candidates[] = rtrim($projectDir, '/').'/'.self::GENERATED_RELATIVE_PATH;
        }

        foreach ($candidates as $path) {
            if (!is_file($path)) {
                continue;
            }
            $data = require $path;
            if (!\is_array($data)) {
                continue;
            }
            $version = $data['version'] ?? null;
            $commit = $data['commit'] ?? null;
            if (!\is_string($version) || '' === $version || !\is_string($commit) || '' === $commit) {
                continue;
            }

            return new self(
                version: $version,
                commit: self::normalizeCommit($commit),
            );
        }

        return null;
    }

    private static function detectGitCommit(?string $projectDir): string
    {
        $cwd = $projectDir;
        if (null === $cwd || '' === $cwd) {
            $cwd = \dirname(__DIR__, 3);
        }

        $cmd = 'git -C '.escapeshellarg($cwd).' rev-parse --short=12 HEAD 2>/dev/null';
        $out = shell_exec($cmd);
        if (!\is_string($out)) {
            return 'unknown';
        }
        $sha = trim($out);

        return '' !== $sha ? self::normalizeCommit($sha) : 'unknown';
    }

    private static function normalizeCommit(string $commit): string
    {
        $commit = trim($commit);
        if ('' === $commit) {
            return 'unknown';
        }

        return $commit;
    }

    private static function env(string $name): ?string
    {
        $value = getenv($name);
        if (false === $value) {
            return null;
        }
        $value = trim($value);

        return '' !== $value ? $value : null;
    }
}
